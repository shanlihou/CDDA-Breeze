# ── CJK 辅助 ──

def has_chinese(s: str) -> bool:
    """判断字符串是否含 CJK 汉字."""
    if not s:
        return False
    for ch in s:
        code = ord(ch)
        if (0x4E00 <= code <= 0x9FFF) or (0x3400 <= code <= 0x4DBF) \
                or (0xF900 <= code <= 0xFAFF):
            return True
    return False


def tokenize_query(query: str) -> list[str]:
    """把查询切成 token. 英文按空格分词,中文按连续 CJK 段切分."""
    tokens: list[str] = []
    if has_chinese(query):
        cur = ""
        for ch in query:
            if has_chinese(ch):
                cur += ch
            else:
                if cur:
                    tokens.append(cur)
                    cur = ""
                if not ch.isspace():
                    tokens.append(ch)
        if cur:
            tokens.append(cur)
    else:
        tokens = query.split()
    return [t for t in tokens if t.strip()]


